import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { makeRng } from '../src/sim/rng';
import { GameWorld } from '../src/game/world';
import { cupXAtTime, simulateShot } from '../src/sim/shot';
import { greedyBestAngle } from '../src/sim/bot';
import type { Flavour } from '../src/sim/types';
import { tokens } from '../src/tokens';

const SPAWN = tokens.layout.pipSpawn;

function median(nums: number[]): number {
  const s = [...nums].sort((a, b) => a - b);
  const m = Math.floor(s.length / 2);
  return s.length % 2 ? s[s.length - 1] : (s[m - 1] + s[m]) / 2;
}

function applyShot(world: GameWorld, angle: number): boolean {
  world.beginShot();
  const cupX = cupXAtTime(world.seed, world.shots + 1);
  const clone = world.bonbons.map((b) => ({ ...b }));
  const res = simulateShot(
    {
      angleRad: angle,
      coat: world.currentCoat,
      spawnX: SPAWN.x,
      spawnY: SPAWN.y,
    },
    clone,
    cupX,
  );
  for (const b of world.bonbons) {
    const c = clone.find((x) => x.id === b.id);
    if (!c) continue;
    b.popped = c.popped;
    b.puffs = c.puffs;
    b.size = c.size;
    b.type = c.type;
    b.expr = c.expr;
  }
  for (const c of res.contacts) {
    if (!c.sameColour && c.bonbon) world.currentCoat = c.bonbon.flavour;
  }
  const caught = res.ended === 'cup';
  world.onShotEnd(caught);
  let guard = 0;
  while (world.rising && guard++ < 400) world.tickRise(1 / 60);
  return caught;
}

function runRandom(seed: string): number {
  const w = new GameWorld(seed, 'rise');
  const rng = makeRng(seed + '-bot');
  while (!w.gameOver && w.shots < 500) {
    const angle = (rng() * 168 - 84) * (Math.PI / 180);
    applyShot(w, angle);
  }
  return w.shots;
}

function runGreedy(seed: string): number {
  const w = new GameWorld(seed, 'rise');
  let coat: Flavour = w.currentCoat;
  while (!w.gameOver && w.shots < 500) {
    w.currentCoat = coat;
    const cupX = cupXAtTime(w.seed, w.shots + 1);
    const angle = greedyBestAngle(seed, w.bonbons, coat, cupX);
    applyShot(w, angle);
    coat = w.currentCoat;
  }
  return w.shots;
}

const randomShots: number[] = [];
const greedyShots: number[] = [];
for (let i = 0; i < 300; i++) {
  const seed = `bal-${i}`;
  randomShots.push(runRandom(seed));
  greedyShots.push(runGreedy(seed));
}

const rs = [...randomShots].sort((a, b) => a - b);
const gs = [...greedyShots].sort((a, b) => a - b);

const report = `# Balance report

Generated by \`npm run balance\` on ${new Date().toISOString().slice(0, 10)}.

Includes **rise + refill** after each shot (unless cup catch).

| bot | median shots | p25 | p75 |
|---|---:|---:|---:|
| random aim | ${median(randomShots).toFixed(1)} | ${rs[Math.floor(rs.length * 0.25)]} | ${rs[Math.floor(rs.length * 0.75)]} |
| greedy (64 angles) | ${median(greedyShots).toFixed(1)} | ${gs[Math.floor(gs.length * 0.25)]} | ${gs[Math.floor(gs.length * 0.75)]} |

GDD target: random median 35–60 shots; greedy > 150 shots.

**Tuning notes:** Greedy survival validates chains + rise/refill after \`simulateShot\` in-place mutation fix. Random median is still below target — continue tuning empty-share, cluster bias, and icing grace (\`FROSTING_MARGIN\` in \`world.ts\`) toward GDD §6.1.
`;

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
writeFileSync(join(root, 'docs/balance.md'), report);
console.log(report);
