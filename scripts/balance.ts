import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { makeRng } from '../src/sim/rng';
import { initialField } from '../src/sim/lattice';
import { cupXAtTime, simulateShot } from '../src/sim/shot';
import { greedyBestAngle } from '../src/sim/bot';
import type { Flavour } from '../src/sim/types';

const SPAWN = { x: 500, y: 235 };

function median(nums: number[]): number {
  const s = [...nums].sort((a, b) => a - b);
  const m = Math.floor(s.length / 2);
  return s.length % 2 ? s[s.length - 1] : (s[m - 1] + s[m]) / 2;
}

function runRandom(seed: string): number {
  const rng = makeRng(seed);
  const { bonbons } = initialField(seed, 5);
  const flavours: Flavour[] = ['berry', 'mint', 'lemon', 'blueberry'];
  let shots = 0;
  let coat: Flavour = flavours[0];
  while (shots < 400) {
    shots++;
    const angle = (rng() * 168 - 84) * (Math.PI / 180);
    coat = flavours[Math.floor(rng() * flavours.length)];
    const res = simulateShot(
      { angleRad: angle, coat, spawnX: SPAWN.x, spawnY: SPAWN.y },
      bonbons,
      cupXAtTime(seed, shots),
    );
    const lastCoat = res.contacts.find((c) => c.bonbon && !c.sameColour)?.bonbon?.flavour;
    if (lastCoat) coat = lastCoat;
    const alive = bonbons.filter((b) => !b.popped);
    if (alive.length < 4) break;
  }
  return shots;
}

function runGreedy(seed: string): number {
  const { bonbons } = initialField(seed, 5);
  let shots = 0;
  let coat: Flavour = 'berry';
  while (shots < 400) {
    shots++;
    const cupX = cupXAtTime(seed, shots);
    const angle = greedyBestAngle(seed, bonbons, coat, cupX);
    const res = simulateShot(
      { angleRad: angle, coat, spawnX: SPAWN.x, spawnY: SPAWN.y },
      bonbons,
      cupX,
    );
    const last = res.contacts.find((c) => c.bonbon && !c.sameColour);
    if (last?.bonbon) coat = last.bonbon.flavour;
    if (bonbons.filter((b) => !b.popped).length < 4) break;
  }
  return shots;
}

const randomShots: number[] = [];
const greedyShots: number[] = [];
for (let i = 0; i < 300; i++) {
  const seed = `bal-${i}`;
  randomShots.push(runRandom(seed));
  greedyShots.push(runGreedy(seed));
}

const report = `# Balance report

Generated by \`npm run balance\` on ${new Date().toISOString().slice(0, 10)}.

| bot | median shots | p25 | p75 |
|---|---:|---:|---:|
| random aim | ${median(randomShots).toFixed(1)} | ${randomShots.sort((a, b) => a - b)[74]} | ${randomShots[224]} |
| greedy (64 angles) | ${median(greedyShots).toFixed(1)} | ${greedyShots.sort((a, b) => a - b)[74]} | ${greedyShots[224]} |

GDD target: random median 35–60 shots; greedy > 150 shots.
`;

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
writeFileSync(join(root, 'docs/balance.md'), report);
console.log(report);
